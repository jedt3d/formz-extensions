def wire_cube(colour=GREY, width=1.6):
    return ''.join(f'<line x1="{p[0]}" y1="{p[1]}" x2="{q[0]}" y2="{q[1]}" stroke="{colour}" '
                   f'stroke-width="{width}" stroke-linecap="round"/>' for p, q in EDGES)


def inset(quad, k):
    cx, cy = sum(p[0] for p in quad) / 4, sum(p[1] for p in quad) / 4
    return [(round(cx + k * (x - cx), 2), round(cy + k * (y - cy), 2)) for x, y in quad]


