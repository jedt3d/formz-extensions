def helix(solid):
    """Loops around a yellow axis; back halves first, then the axis, then front halves."""
    ys = [10.5, 17.5, 25, 32.5, 40]
    def half(y, front):
        return f'M4.5 {y} A19 4.6 0 0 {0 if front else 1} 42.5 {y}'
    if solid:
        draw = lambda d: path(d, width=4.8) + path(d, width=2.4, colour=TOP)
    else:
        draw = lambda d: path(d, width=1.8)
    return (''.join(draw(half(y, False)) for y in ys) + axis(23.5, 2.5, 46)
            + ''.join(draw(half(y, True)) for y in ys))


