"""Write the 3D pilot masters (Cube, Extrusion, Revolve, Fillet, Paint) traced
over formZ's own 48 px icons: same silhouette, faces and viewpoint, drawn as
navy outlines with flat fills. Coordinates are read from the originals on a
48-unit grid. Pick (3169) is approved and generated by pick_arrow.py instead.
usage: python3 gen_traced3d.py <masters dir>
"""
import math
import os
import sys

OUT = sys.argv[1]
N, Y, A, L = '#1F3550', '#F2C200', '#E0362C', '#DCEBF7'
TOP, MID, DARK = '#8EC3EE', '#4F95D6', '#2F6DB0'
GHOST, DEEP_RED = '#C9CED6', '#A3241C'
ST = f'stroke="{N}" stroke-width="2" stroke-linejoin="round" stroke-linecap="round"'


def svg(body):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" width="48" height="48">{body}</svg>'


def poly(pts, fill, extra=''):
    return f'<path d="M{" L".join(f"{x} {y}" for x, y in pts)} Z" fill="{fill}" {ST}{extra}/>'


icons = {}

# Cube 3280: top face, front face, right face (formZ's view from above left)
icons[3280] = (poly([(16, 3), (42.5, 4.5), (36, 20.5), (5.5, 16.5)], TOP)
               + poly([(5.5, 16.5), (36, 20.5), (35.5, 45.5), (7, 40.5)], MID)
               + poly([(36, 20.5), (42.5, 4.5), (41.5, 38), (35.5, 45.5)], DARK))

# Extrusion 3422: solid upper block, see-through lower block, red arrow up
icons[3422] = (poly([(4.5, 27), (33, 30), (32, 43.5), (7, 39.5)], GHOST)
               + poly([(33, 30), (38.5, 16.5), (37.5, 31.5), (32, 43.5)], GHOST)
               + poly([(15, 2), (38.5, 5), (33, 18.5), (4, 15)], TOP)
               + poly([(4, 15), (33, 18.5), (33, 30), (4.5, 27)], MID)
               + poly([(33, 18.5), (38.5, 5), (38.5, 16.5), (33, 30)], DARK)
               + f'<path d="M39.3 17.5 L39.6 23.5 L42.4 23.3 L42.1 17.5 L46 18 L41.3 9.5 L36.6 17.4 Z" '
                 f'fill="{A}" stroke="{N}" stroke-width="1.4" stroke-linejoin="round"/>')

# Revolve 3023: wide dish on top, body below with the right quarter cut away
# to show the profile, yellow axis through the middle
icons[3023] = (f'<path d="M8 19 C5.5 25 6 32 10 37.5 C13.5 42.5 18 46.5 24.5 47 L24.5 19 Z" fill="{MID}" {ST}/>'
               + f'<path d="M24.5 19 L42 19 C45 23 45.5 27 44 30 L29.5 30 C30.5 35 33.5 38.5 37.5 41 '
                 f'C33 43.5 28.5 44.5 24.5 44.5 Z" fill="{DARK}" {ST}/>'
               + f'<path d="M19.5 20 C18 26 21.5 30 21.5 34 C21.5 38.5 19.5 41 19.5 46" fill="none" stroke="{N}" stroke-width="2.4" stroke-linecap="round"/>'
               + f'<ellipse cx="24" cy="11" rx="19.5" ry="8.5" fill="{TOP}" {ST}/>'
               + f'<ellipse cx="24" cy="11.6" rx="14.5" ry="5.3" fill="{MID}" stroke="{N}" stroke-width="1.4"/>'
               + f'<line x1="24.5" y1="2.5" x2="24.5" y2="46.5" stroke="{N}" stroke-width="3.8" stroke-linecap="round"/>'
               + f'<line x1="24.5" y1="2.5" x2="24.5" y2="46.5" stroke="{Y}" stroke-width="2" stroke-linecap="round"/>')

# Fillet 3480: slab, yellow fillet ring with wireframe, sphere on top
ring = []
for a in (5, 30, 55, 90, 125, 150, 175):
    r = math.radians(a)
    x0, y0 = 24 + 8.5 * math.cos(r), 22.5 + 2.6 * math.sin(r)
    x1, y1 = 24 + 13.5 * math.cos(r), 26 + 4.6 * math.sin(r)
    ring.append(f'<line x1="{x0:.2f}" y1="{y0:.2f}" x2="{x1:.2f}" y2="{y1:.2f}" stroke="{N}" stroke-width="1"/>')
icons[3480] = (poly([(5.5, 27.5), (13.5, 21.5), (41.5, 20.5), (32, 32.5)], TOP)
               + poly([(5.5, 27.5), (32, 32.5), (32, 46), (7, 41.5)], MID)
               + poly([(32, 32.5), (41.5, 20.5), (41, 37.5), (32, 46)], DARK)
               + f'<ellipse cx="24" cy="26" rx="13.5" ry="4.6" fill="{Y}" {ST}/>'
               + ''.join(ring)
               + f'<path d="M12.5 24.2 A11.6 3.4 0 0 0 35.5 24.2" fill="none" stroke="{N}" stroke-width="1"/>'
               + f'<circle cx="24" cy="12" r="11" fill="{MID}" {ST}/>'
               + f'<ellipse cx="20" cy="8.5" rx="5.2" ry="4.2" fill="{TOP}"/>')

# Paint 7235: can tilted 44 degrees, opening at the upper right with paint
# inside, red paint spilling down the right side
can = (f'<g transform="translate(34 18) rotate(44)">'
       f'<path d="M-13 0 L-13 28 A13 6.5 0 0 0 0 34.5 L0 6.5 A13 6.5 0 0 1 -13 0 Z" fill="{MID}" {ST}/>'
       f'<path d="M0 6.5 L0 34.5 A13 6.5 0 0 0 13 28 L13 0 A13 6.5 0 0 1 0 6.5 Z" fill="{DARK}" {ST}/>'
       f'<ellipse cx="0" cy="0" rx="13" ry="6.5" fill="{L}" {ST}/>'
       f'<ellipse cx="0" cy="0.4" rx="10.4" ry="4.6" fill="{DEEP_RED}" stroke="{N}" stroke-width="1.3"/>'
       f'</g>')
icons[7235] = (can + f'<path d="M28.5 27.5 C30.5 33 33 40.5 38 40.5 C43.5 40.5 45.5 33 44.5 24.5 '
                     f'C41 27.5 34 29 28.5 27.5 Z" fill="{A}" {ST}/>')

for i, body in sorted(icons.items()):
    open(os.path.join(OUT, f'Cic_{i}.svg'), 'w').write(svg(body))
print(f'wrote {len(icons)} masters')
