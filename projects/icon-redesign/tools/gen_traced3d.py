GREY = '#8A9BB0'  # formZ's thin grey wire lines


def path(d, fill='none', width=2, colour=N):
    return (f'<path d="{d}" fill="{fill}" stroke="{colour}" stroke-width="{width}" '
            f'stroke-linejoin="round" stroke-linecap="round"/>')


def tube(d, outer=11, inner=7.6):
    """Swept tube: navy outline with a light body along path d."""
    return path(d, width=outer) + path(d, width=inner, colour=TOP)


def ell(cx, cy, rx, ry, fill, rot=0, width=2):
    tr = f' transform="rotate({rot} {cx} {cy})"' if rot else ''
    return f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}"{tr} fill="{fill}" stroke="{N}" stroke-width="{width}"/>'


def axis(x, y0, y1):
    return (f'<line x1="{x}" y1="{y0}" x2="{x}" y2="{y1}" stroke="{N}" stroke-width="3.8" stroke-linecap="round"/>'
            f'<line x1="{x}" y1="{y0}" x2="{x}" y2="{y1}" stroke="{Y}" stroke-width="2" stroke-linecap="round"/>')


